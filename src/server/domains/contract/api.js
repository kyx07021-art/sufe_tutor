// Ledger chain (contract_ledger): hash-chain evidence of signed bodies.
// ============================================================
const sha256Hex = text => crypto.subtle.digest('SHA-256', new TextEncoder().encode(text)).then(bufToHex);

// Chain hash material must cover body + contract_id + created_at + prev_hash, otherwise a DB
// writer could rebuild the whole ledger undetected. The body hash is taken first (avoid
// re-hashing a long body), then chained with the metadata.
async function ledgerContentHash(contractId, contractMd, createdAt, prevHash) {
  const bodyHash = await sha256Hex(contractMd);
  return sha256Hex(`${bodyHash}|${contractId}|${createdAt}|${prevHash}`);
}

// Record a signed body onto the chain: prev/seq are filtered per contract (each contract is an
// independent chain rooted at GENESIS). The prev read, seq allocation and insert happen in a
// single conditional INSERT — a concurrent fork (prev changed in DB) lands changes=0, retried
// after re-reading. Idempotent: same contract + same body hash returns the existing hash
// (a retry after a signed-then-500 may safely backfill without double-linking).
// Idempotency key = contract_id + body_hash (time-decoupled; content_hash contains a second-level
// createdAt, so it cannot be the dedup key across seconds).
export async function ledgerRecord(db, contractId, contractMd) {
  const target = getLedgerDb(db);
  const bodyHash = await sha256Hex(contractMd);
  const createdAt = toDbTime();
  for (let i = 0; i < 3; i++) {
    const prev = await dbGet(target, 'SELECT content_hash FROM contract_ledger WHERE contract_id=? ORDER BY id DESC LIMIT 1', [contractId]);
    const prevHash = prev ? prev.content_hash : 'GENESIS';
    const contentHash = await ledgerContentHash(contractId, contractMd, createdAt, prevHash);
    const r = await dbRun(target, `INSERT INTO contract_ledger (contract_id, content_hash, prev_hash, seq, body_hash, created_at)
      SELECT ?, ?, COALESCE((SELECT content_hash FROM contract_ledger WHERE contract_id=? ORDER BY id DESC LIMIT 1),'GENESIS'),
             COALESCE((SELECT MAX(seq) FROM contract_ledger WHERE contract_id=?),0)+1, ?, ?
      WHERE COALESCE((SELECT content_hash FROM contract_ledger WHERE contract_id=? ORDER BY id DESC LIMIT 1),'GENESIS') = ?
        AND NOT EXISTS (SELECT 1 FROM contract_ledger WHERE contract_id=? AND body_hash=?)`,
      [contractId, contentHash, contractId, contractId, bodyHash, createdAt, contractId, prevHash, contractId, bodyHash]);
    if (r.meta.changes > 0) return contentHash;
    // changes=0: either a lost chain-tail race or an existing entry — if the same body was already
    // recorded, return its existing hash (latest row).
    const dup = await dbGet(target, 'SELECT content_hash FROM contract_ledger WHERE contract_id=? AND body_hash=? ORDER BY id DESC LIMIT 1', [contractId, bodyHash]);
    if (dup) return dup.content_hash;
  }
  throw new Error('ledger insert retry exhausted'); // 3 failed tail races: fail the request, never silently break the chain
}

// Walk the whole chain: GENESIS head + adjacent prev_hash continuity + monotonic seq.
// Historical bodies are not in the DB (a contract may be edited across versions) — tampering with
// any historical content_hash breaks the link to the next entry's prev_hash. The latest body can
// be replayed when opts carry the current body; revoked (archived) contracts do structure-only
// validation (no body to replay).
export async function verifyChain(rows, opts = {}) {
  const headValid = rows.length ? rows[0].prev_hash === 'GENESIS' : false;
  let linksValid = true, seqValid = true;
  for (let i = 1; i < rows.length; i++) {
    if (rows[i].prev_hash !== rows[i - 1].content_hash) linksValid = false;
    if (rows[i].seq != null && rows[i - 1].seq != null && rows[i].seq !== rows[i - 1].seq + 1) seqValid = false;
  }
  let lastRehashValid = null;
  if (rows.length && !opts.archived && opts.contractId != null && opts.contractMd != null) {
    const last = rows[rows.length - 1];
    lastRehashValid = (await ledgerContentHash(opts.contractId, opts.contractMd, last.created_at, last.prev_hash)) === last.content_hash;
  }
  return { headValid, linksValid, seqValid, lastRehashValid, ok: headValid && linksValid && seqValid };
}

// Verify a contract's ledger: full chain walk + latest body replay. A revoked contract row keeps
// its ledger; the response reports archived=true and does structure-only validation.
export async function verifyContractLedger(db, contractId) {
  const rows = await dbAll(getLedgerDb(db),
    'SELECT id, contract_id, content_hash, prev_hash, seq, body_hash, created_at FROM contract_ledger WHERE contract_id=? ORDER BY id ASC', [contractId]);
  if (!rows.length) return { recorded: false };
  const ct = await dbGetContractById(db, contractId);
  const archived = !ct;
  const chain = await verifyChain(rows, archived ? {} : { contractId, contractMd: ct.contract_md });
  const last = rows[rows.length - 1];
  return {
    recorded: true, archived,
    valid: chain.ok && chain.lastRehashValid !== false, // archived: no body to replay (lastRehashValid=null), structure only
    entries: rows.length, headValid: chain.headValid, linksValid: chain.linksValid, seqValid: chain.seqValid,
    contentHash: last.content_hash, prevHash: last.prev_hash, createdAt: last.created_at,
    entryList: rows.map(r => ({ seq: r.seq, createdAt: r.created_at })),
  };
}

// ---- Party determination helpers ----
// These operate on the contract's own tuple (student_user_id / teacher_user_id) — conversation_id
// is nullable and a conversation may be deleted, so the contract row itself must decide who may
// operate. The same helper also works on conversation rows (they share the tuple shape).
export const isParticipant = (ct, userId) => !!ct && (ct.student_user_id === userId || ct.teacher_user_id === userId);
export const otherSide = (ct, userId) => userId === ct.student_user_id ? ct.teacher_user_id : ct.student_user_id;
// conv is only used for display names (notifications); null-safe because conversation_id is nullable.
export const nameOf = (conv, userId) => conv ? (userId === conv.student_user_id ? conv.student_name : conv.teacher_name) : '';

// Shared gate for contract operations: load row (404) -> status whitelist (409) -> participant
// check on the contract tuple (403). conv is fetched only as a naming/lifecycle source and may be
// null when the conversation is gone. Failures return { err: Response }; callers return g.err.
export async function loadContractFor(db, contractId, userId, statuses) {
  const ct = await dbGetContractById(db, contractId);
  if (!ct) return { err: errorMsg('CONTRACT_NOT_FOUND', 404) };
  if (!statuses.includes(ct.status)) return { err: errorMsg('CONTRACT_STATE_INVALID', 409) };
  if (!isParticipant(ct, userId)) return { err: errorMsg('NO_PERMISSION', 403) };
  const conv = ct.conversation_id ? await dbGetConversationWithNames(db, ct.conversation_id) : null;
  return { ct, conv };
}

