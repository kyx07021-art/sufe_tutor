/**
 * Contract domain — standalone model (S5). The contract is an independent record, decoupled from
 * demands and from the conversation lifecycle:
 *   - `contracts` table carries its own party tuple (student_user_id / teacher_user_id).
 *   - `conversation_id` is a nullable historical link (no FK cascade — deleting a conversation
 *     never deletes signed/revoked contracts, which are retained as evidence).
 *   - State machine: draft (signing) -> double confirmation -> signed; revoke marks revoked=1
 *     (the row and its ledger chain are kept); cancel rolls one side back to signing.
 *   - The ledger chain (contract_ledger) fingerprints every signed body hash; verify rehashes
 *     the latest entry and walks prev_hash links to detect any tampering.
 *   - Dangerous operations (draft / sign / revoke / cancel / admin remove) require a fresh
 *     capToken via danger-ops.confirmDangerOtp.
 *
 * The full contract body is generated by buildContractMd (business clauses) + fixed legal clauses
 * (LEGAL_CLAUSES) + signature block (buildSignatureBlock). Only the business section is editable.
 */
