// POST /api/contracts { conversationId, method, plan, rate, schedule, location, payMethod, ... }
// Draft a new standalone contract and send it to the other party. Full self-contained INSERT —
// no demand gate, no stage promotion, no conversation mutation. Requires capToken.
export async function handleCreateContract(db, body, req) {
  const { user: me, err: authErr } = await requireUser(db, req);
  if (authErr) return authErr;
  const userId = me.id;
  const conversationId = parseInt(body.conversationId, 10);
  // AF-5: illegal conversationId (parseInt(null)=NaN) must never reach D1 binding
  if (!Number.isInteger(conversationId) || conversationId <= 0) return errorMsg('INVALID_PARAMS', 404);
  const conv = await dbGetConversationWithNames(db, conversationId);
  if (!isParticipant(conv, userId)) return errorMsg('NO_PERMISSION', 403);
  // Closed conversations are read-only for both parties (no drafting)
  if (conv.status !== STATUS.ACTIVE) return errorMsg('NO_PERMISSION', 403);

  // Teacher acceptance eligibility (chsi verification + profile completeness) — checked on the
  // conversation's teacher (the drafter may be either party).
  const teacherId = me.role === 'teacher' ? userId : conv.teacher_user_id;
  const tProf = await dbGetTeacherProfile(db, teacherId);
  const el = acceptEligibility(tProf);
  if (!el.ok) {
    const key = el.reason === 'CHSI_UNVERIFIED' ? 'CHSI_VERIFY_REQUIRED' : 'PROFILE_COMPLETE_REQUIRED';
    return errorMsg(key, 403, el.reason || undefined);
  }

  // Drafting commits binding terms — dangerous operation, requires a fresh capToken
  if (!(await confirmDangerOtp(db, req, body))) return errorMsg('REAUTH_FAILED', 403);

  const method = body.method === 'offline' ? 'offline' : 'online';
  const plan = String(body.plan || '').slice(0, LIMITS.CONTRACT_PLAN_MAX);
  const rate = Math.min(LIMITS.BUDGET_MAX, Math.max(0, parseInt(body.rate) || 0)); // hourly rate clamped to BUDGET_MAX
  const schedule = String(body.schedule || '').slice(0, LIMITS.CONTRACT_SCHEDULE_MAX);
  const location = String(body.location || '').slice(0, LIMITS.CONTRACT_LOCATION_MAX);
  // Pay/trial three-element sets: whitelist enums + "other" free text; first lesson date yyyy-mm-dd
  const payMethod = ['per_session', 'weekly', 'monthly', 'other'].includes(body.payMethod) ? body.payMethod : '';
  const payMethodOther = payMethod === 'other' ? String(body.payMethodOther || '').trim().slice(0, LIMITS.PAY_OTHER_MAX) : '';
  if (payMethod === 'other' && !payMethodOther) return errorMsg('INVALID_PARAMS', 400);
  const firstLessonDate = /^\d{4}-\d{2}-\d{2}$/.test(String(body.firstLessonDate || '')) ? body.firstLessonDate : '';
  const trialPay = ['first_free', 'first_hour_free', 'normal', 'other'].includes(body.trialPay) ? body.trialPay : '';
  const trialPayOther = trialPay === 'other' ? String(body.trialPayOther || '').trim().slice(0, LIMITS.PAY_OTHER_MAX) : '';
  if (trialPay === 'other' && !trialPayOther) return errorMsg('INVALID_PARAMS', 400);

  const md = buildContractMd({
    teacherName: conv.teacher_name, studentName: conv.student_name,
    method, schedule, location, plan, rate, createdAt: new Date().toISOString().slice(0, 10),
    payMethod, payMethodOther, firstLessonDate, trialPay, trialPayOther,
  });
  const mdEnc = await encryptField(md); // contract body encrypted at rest (repo decrypts on read)
  // Independent contract row: full self-contained insert, no demand gate / no stage / no fallback
  const id = await dbCreateContract(db, {
    conversationId, studentUserId: conv.student_user_id, teacherUserId: conv.teacher_user_id,
    drafterUserId: userId, method, plan, rate, schedule, location,
    payMethod, payMethodOther, firstLessonDate, trialPay, trialPayOther,
    contractMd: mdEnc,
  });
  // Persist the body including the (all-pending) signature block
  const fullMd = md + buildSignatureBlock({
    studentName: conv.student_name, teacherName: conv.teacher_name,
    studentSignedAt: '', teacherSignedAt: '', contractId: id,
  });
  await dbSetContractMd(db, id, await encryptField(fullMd));
  // Contract event bubble visible to both parties in the conversation
  await dbCreateMessage(db, conversationId, userId, 'contract', 'contract_draft');
  await notifyUser(db, otherSide(conv, userId), 'CONTRACT_DRAFT_SENT', { name: nameOf(conv, userId) });
  await logEvent(db, { action: 'contract.create', actorUserId: userId, entity: 'contract', entityId: id,
    detail: { conversationId, method, rate }, req });
  return json({ id, message: UIC.CONTRACT_DRAFT_SENT_TOAST }, 201);
}

// GET /api/contracts -> { contracts } (my contracts, both roles)
export async function handleGetMyContracts(db, url, req) {
  const { user: me, err } = await requireUser(db, req);
  if (err) return err;
  return json({ contracts: await dbGetMyContracts(db, me.id) });
}

// GET /api/contracts/:id -> { contract } (participants and admin only)
export async function handleGetContractById(db, contractId, req) {
  const { user: me, err } = await requireUser(db, req);
  if (err) return err;
  const ct = await dbGetContractById(db, contractId);
  if (!ct) return errorMsg('CONTRACT_NOT_FOUND', 404);
  const isAdmin = requireAdminOrError(me) === null;
  if (!isAdmin && !isParticipant(ct, me.id)) return errorMsg('NO_PERMISSION', 403);
  return json({ contract: ct });
}

// POST /api/contracts/:id/sign — confirm signing; both confirmations move status -> signed.
// SIGNED is accepted so a retry after a signed-then-ledger-failure can idempotently backfill.
export async function handleSignContract(db, contractId, body, req) {
  const { user: me, err: authErr } = await requireUser(db, req);
  if (authErr) return authErr;
  const userId = me.id;
  const g = await loadContractFor(db, contractId, userId, [CONTRACT_STATUS.SIGNING, CONTRACT_STATUS.SIGNED]);
  if (g.err) return g.err;
  const { ct, conv } = g;
  // Lifecycle gate: a closed/deleted conversation forbids contract writes; retained evidence stays
  if (!conv || conv.status !== STATUS.ACTIVE) return errorMsg('CONVERSATION_CLOSED', 403);
  // Revoked contracts (status still 'signed') reject any further sign — checked before capToken
  // consumption so a stale one-time code is not spent.
  if (ct.revoked) return errorMsg('CONTRACT_ALREADY_REVOKED', 409);
  // Dangerous operation (binding transaction): fresh capToken required
  if (!(await confirmDangerOtp(db, req, body))) return errorMsg('REAUTH_FAILED', 403);

  const col = userId === ct.drafter_user_id ? 'drafter_confirmed' : 'other_confirmed';
  const signedCol = userId === ct.drafter_user_id ? 'drafter_signed_at' : 'other_signed_at';
  // Conditional UPDATE + changes winner: the status guard means a contract already cancelled or
  // signed produces no change; the changes=0 side reloads and returns idempotently. version bumps.
  const flag = await dbRun(db, `UPDATE contracts SET ${col}=1, ${signedCol}=datetime('now'), contract_status='signing', version=version+1, updated_at=datetime('now') WHERE id=? AND contract_status IN ('signing')`, [contractId]);
  if (!(flag && flag.meta && flag.meta.changes > 0)) {
    const cur = await loadContractFor(db, contractId, userId, [CONTRACT_STATUS.SIGNING, CONTRACT_STATUS.SIGNED]);
    if (cur.err) return cur.err;
    // Previous round already signed but the ledger write failed (500): idempotent backfill
    if (cur.ct.status === CONTRACT_STATUS.SIGNED) {
      try { await ledgerRecord(db, contractId, cur.ct.contract_md); }
      catch (e) { console.error('contract ledger backfill failed:', e && e.message); }
    }
    return json({ ok: true, signed: cur.ct.status === CONTRACT_STATUS.SIGNED });
  }
  const updated = await dbGetContractById(db, contractId);
  if (!updated) return errorMsg('CONTRACT_NOT_FOUND', 404); // concurrent revoke removed the row: clean 404
  const both = !!(updated.drafter_confirmed && updated.other_confirmed);
  // Rebuild the signature block (names + timestamps) and write back with a version optimistic lock —
  // under concurrent double-sign only the last landing body wins (stale body changes=0 discarded).
  const signedMd = rebuildFullMd(updated, conv);
  const mdUpdate = await dbRun(db, `UPDATE contracts SET contract_md=?, version=version+1 WHERE id=? AND version=?`,
    [await encryptField(signedMd), contractId, updated.version]);
  // Loser of the double-sign race: skip ledger/notify/log (the winner already recorded)
  if (!(mdUpdate && mdUpdate.meta && mdUpdate.meta.changes > 0)) {
    return json({ ok: false, signed: false });
  }
  // Every sign records the ledger: body embeds who/when, content_hash covers it; idempotent
  // (same body NOT EXISTS) so concurrent double-sign appends one entry and retries backfill safely.
  let contentHash = '';
  try { contentHash = await ledgerRecord(db, contractId, signedMd); }
  catch (e) {
    // Ledger failure must neither 500 (deadlock on a both-confirmed signing) nor be silent — the
    // gap is exposed via the verify panel (recorded=false) and a ledgerFailed audit flag; retry
    // goes through the SIGNED backfill branch above.
    console.error('contract ledger failed:', e && e.message);
    contentHash = '';
  }
  if (both) {
    // Conditional winner: only one side's claim changes>0, preventing duplicate notifications
    const claim = await dbRun(db, `UPDATE contracts SET contract_status='signed', prev_business=NULL, version=version+1 WHERE id=? AND contract_status='signing'`, [contractId]);
    if (claim && claim.meta && claim.meta.changes > 0) {
      await notifyUser(db, otherSide(conv, userId), 'CONTRACT_SIGNED', {});
      // Audit saves the signed body (detailMax widened, encrypted) — retained even after revoke
      await logEvent(db, { action: 'contract.signed', actorUserId: userId, entity: 'contract', entityId: contractId,
        detail: { conversationId: updated.conversation_id, contentHash,
          ...(contentHash ? {} : { ledgerFailed: true }), contractMd: signedMd },
        detailMax: 60000, req });
    }
  } else {
    await notifyUser(db, otherSide(conv, userId), 'CONTRACT_SIGN_WAITING', { name: nameOf(conv, userId) });
    await logEvent(db, { action: 'contract.sign_partial', actorUserId: userId, entity: 'contract', entityId: contractId,
      detail: { signedBy: userId, contentHash, ...(contentHash ? {} : { ledgerFailed: true }), contractMd: signedMd }, detailMax: 60000, req });
  }
  return json({ ok: true, signed: both });
}

// PUT /api/contracts/:id { contractMd, version } — edit the contract: reset both confirmations,
// sync the other party in real time. Optimistic lock on the integer version; version mismatch or
// status left 'signing' -> 409 forces a client reload.
export async function handleModifyContract(db, contractId, body, req) {
  const { user: me, err: authErr } = await requireUser(db, req);
  if (authErr) return authErr;
  const userId = me.id;
  const g = await loadContractFor(db, contractId, userId, [CONTRACT_STATUS.SIGNING]);
  if (g.err) return g.err;
  const { ct, conv } = g;
  // Lifecycle gate: closed relationship forbids edits (historical evidence retained)
  if (!conv || conv.status !== STATUS.ACTIVE) return errorMsg('CONVERSATION_CLOSED', 403);
  // A party that already confirmed cannot edit (editing resets both confirmations = withdrawing
  // one's own commitment). The unconfirmed party may still edit after the other signed.
  const myConfirmed = userId === ct.drafter_user_id ? !!ct.drafter_confirmed : !!ct.other_confirmed;
  if (myConfirmed) return errorMsg('CONTRACT_LOCKED_AFTER_SIGN', 409);
  const ver = parseInt(body.version);
  if (!Number.isInteger(ver)) return errorMsg('INVALID_PARAMS', 400);
  // The edit modal only exposes the business section — the legal section is re-appended server-side.
  // Strip any residual marker and trailing content (defense against full-body / duplicate submits).
  const md = String(body.contractMd || '').slice(0, LIMITS.CONTRACT_MD_MAX).split(CONTRACT_BUSINESS_END)[0].trim();
  if (!md) return error(UIC.CONTRACT_EMPTY, 400, 'CONTRACT_EMPTY');
  // Old-format contracts (no marker): the whole body is business — do not append a legal block,
  // otherwise the old legal text would be treated as business and duplicated.
  const oldHasMarker = (ct.contract_md || '').includes(CONTRACT_BUSINESS_END);
  const oldBiz = (oldHasMarker ? (ct.contract_md || '').split(CONTRACT_BUSINESS_END)[0] : (ct.contract_md || '')).trim();
  if (md === oldBiz) return json({ ok: true, unchanged: true }); // business unchanged: no reset, no re-notify
  // New format: business + legal + signature block (all pending — edit rolls back the sign choice);
  // old format: keep verbatim (no marker -> no signature block, historical semantics intact)
  const fullMd = oldHasMarker
    ? contractWithLegal(md) + buildSignatureBlock({
        studentName: conv.student_name, teacherName: conv.teacher_name,
        studentSignedAt: '', teacherSignedAt: '', contractId,
      })
    : md;

  // Edit returns to the signing-selection state: both confirmations + signed timestamps cleared,
  // prev_business keeps the diff baseline; optimistic lock lands in SQL WHERE (exact version)
  const upd = await dbRun(db,
    `UPDATE contracts SET contract_md=?, prev_business=?, drafter_confirmed=0, other_confirmed=0,
       drafter_signed_at='', other_signed_at='', contract_status='signing', version=version+1, updated_at=datetime('now')
     WHERE id=? AND version=? AND contract_status IN ('signing')`,
    [await encryptField(fullMd), await encryptField(oldBiz), contractId, ver]);
  if (!(upd && upd.meta && upd.meta.changes > 0)) return errorMsg('CONTRACT_MODIFIED_CONFLICT', 409, 'CONTRACT_MODIFIED_CONFLICT');
  await notifyUser(db, otherSide(conv, userId), 'CONTRACT_MODIFIED', { name: nameOf(conv, userId) });
  await logEvent(db, { action: 'contract.modify', actorUserId: userId, entity: 'contract', entityId: contractId, req });
  return json({ ok: true });
}

// POST /api/contracts/:id/revoke — revoke a signed contract (mutually agreed termination only):
// the row is kept with revoked=1 (evidence retained), the ledger and encrypted audit stay.
export async function handleRevokeContract(db, contractId, body, req) {
  const { user: me, err: authErr } = await requireUser(db, req);
  if (authErr) return authErr;
  const g = await loadContractFor(db, contractId, me.id, [CONTRACT_STATUS.SIGNED]); // unsigned goes through cancel
  if (g.err) return g.err;
  const { ct, conv } = g;
  // Lifecycle gate: closing the relationship first forbids revoke (must revoke before closing)
  if (!conv || conv.status !== STATUS.ACTIVE) return errorMsg('CONVERSATION_CLOSED', 403);
  if (ct.revoked) return errorMsg('CONTRACT_ALREADY_REVOKED', 409); // idempotent rejection
  if (!(await confirmDangerOtp(db, req, body))) return errorMsg('REAUTH_FAILED', 403); // dangerous operation
  // Revoke marks the row (does not delete): body + ledger retained for evidence; conditional
  // UPDATE so only one of two concurrent revokers runs the side effects.
  const upd = await dbRun(db,
    `UPDATE contracts SET revoked=1, revoked_by=?, contract_status='signed', version=version+1, updated_at=datetime('now')
     WHERE id=? AND revoked=0`, [me.id, contractId]);
  if (!(upd && upd.meta && upd.meta.changes > 0)) {
    const cur = await dbGetContractById(db, contractId);
    if (cur && cur.revoked) return errorMsg('CONTRACT_ALREADY_REVOKED', 409); // concurrent revoke
    return errorMsg('CONTRACT_NOT_FOUND', 404);
  }
  await notifyUser(db, otherSide(conv, me.id), 'CONTRACT_REVOKED', { name: nameOf(conv, me.id) });
  await logEvent(db, { action: 'contract.revoke', actorUserId: me.id, entity: 'contract', entityId: contractId,
    detail: { conversationId: ct.conversation_id, note: 'contract_retained' }, req });
  return json({ ok: true });
}

// GET /api/contracts/:id/verify — ledger verification: rehash the text against the chain.
// Read-only evidence check, exempt from the lifecycle gate (historical evidence stays verifiable
// after the relationship is closed). Participants and admin only (tuple-based).
export async function handleVerifyContract(db, contractId, req) {
  const { user: me, err: authErr } = await requireUser(db, req);
  if (authErr) return authErr;
  const ct = await dbGetContractById(db, contractId);
  if (!ct) return errorMsg('CONTRACT_NOT_FOUND', 404);
  const isAdmin = requireAdminOrError(me) === null;
  if (!isAdmin && !isParticipant(ct, me.id)) return errorMsg('NO_PERMISSION', 403);
  return json(await verifyContractLedger(db, contractId));
}

