// DELETE /api/admin/contracts/:id — admin remove (backoffice/test; full audit trail kept, removal
// logged as admin.contract.remove). Dangerous operation: capToken required.
export async function handleAdminRemoveContract(db, contractId, body, req) {
  const { admin, err } = await requireAdmin(db, req);
  if (err) return err;
  const ct = await dbGetContractById(db, contractId);
  if (!ct) return errorMsg('CONTRACT_NOT_FOUND', 404);
  if (!(await confirmDangerOtp(db, req, body))) return errorMsg('REAUTH_FAILED', 403);
  await dbDeleteContract(db, contractId);
  await logEvent(db, { action: 'admin.contract.remove', actorUserId: admin.id, actorUsername: admin.username,
    actorRole: 'admin', entity: 'contract', entityId: contractId,
    detail: { conversationId: ct.conversation_id, status: ct.status, drafterUserId: ct.drafter_user_id }, req });
  return json({ ok: true });
}

// DELETE /api/contracts/:id — cancel signing (row kept, never deleted):
//   ① my side signed, other not: cancel rolls my side back to signing (clear my confirmed +
//      signed_at), the contract stays clean and can be re-signed.
//   ② both signed: rejected (409) — that path is POST /api/contracts/:id/revoke.
// Cancellation always rolls status back to 'signing' ('pending' was the legacy draft-confirmation
// state; new contracts are created directly as 'signing').
export async function handleCancelContract(db, contractId, body, req) {
  const { user: me, err: authErr } = await requireUser(db, req);
  if (authErr) return authErr;
  const userId = me.id;
  const g = await loadContractFor(db, contractId, userId, [CONTRACT_STATUS.SIGNING]);
  if (g.err) return g.err;
  const { ct, conv } = g;
  // Lifecycle gate: closed relationship forbids cancelling a signing
  if (!conv || conv.status !== STATUS.ACTIVE) return errorMsg('CONVERSATION_CLOSED', 403);
  // Dangerous operation (withdrawing a signing commitment): capToken required
  if (!(await confirmDangerOtp(db, req, body))) return errorMsg('REAUTH_FAILED', 403);

  const myCol = userId === ct.drafter_user_id ? 'drafter_confirmed' : 'other_confirmed';
  const theirCol = userId === ct.drafter_user_id ? 'other_confirmed' : 'drafter_confirmed';
  const mySigned = userId === ct.drafter_user_id ? !!ct.drafter_confirmed : !!ct.other_confirmed;
  const bothSigned = mySigned && (!!ct[theirCol]);
  if (bothSigned) return errorMsg('CONTRACT_CANCEL_SIGNED_BLOCKED', 409); // both signed: use revoke

  // Conditional UPDATE concurrent guard: AND current status; the changes=0 side reloads and
  // returns idempotently (no side effects when the other side concurrently signed/changed state).
  // Rolls back my confirmation + signed_at, status -> 'signing' (clean "await my sign" state).
  const upd = await dbRun(db,
    `UPDATE contracts SET ${myCol}=0,
        ${userId === ct.drafter_user_id ? "drafter_signed_at=''" : "other_signed_at=''"},
        contract_status='signing', version=version+1, updated_at=datetime('now')
     WHERE id=? AND contract_status IN ('signing')`, [contractId]);
  if (!(upd && upd.meta && upd.meta.changes > 0)) {
    const cur = await dbGetContractById(db, contractId);
    if (cur && cur.status === CONTRACT_STATUS.SIGNED && !cur.revoked) return errorMsg('CONTRACT_CANCEL_SIGNED_BLOCKED', 409);
    return json({ ok: true }); // concurrent cancel: idempotent
  }
  // Rebuild the signature block reflecting my rolled-back sign state; version optimistic lock
  // with at most two rounds (a concurrent edit mid-rebuild is re-read and re-built once).
  let curCt = await dbGetContractById(db, contractId);
  if (curCt && curCt.status === CONTRACT_STATUS.SIGNING) {
    for (let i = 0; i < 2; i++) {
      const mdUpd = await dbRun(db, `UPDATE contracts SET contract_md=?, version=version+1 WHERE id=? AND version=?`,
        [await encryptField(rebuildFullMd(curCt, conv)), contractId, curCt.version]);
      if (mdUpd && mdUpd.meta && mdUpd.meta.changes > 0) break;
      curCt = await dbGetContractById(db, contractId); // concurrent advance: re-read latest version
      if (!curCt || curCt.status !== CONTRACT_STATUS.SIGNING) break;
    }
  }
  await notifyUser(db, otherSide(conv, userId), 'CONTRACT_CANCELLED', { name: nameOf(conv, userId) });
  await logEvent(db, { action: 'contract.cancel', actorUserId: userId, entity: 'contract', entityId: contractId,
    detail: { conversationId: ct.conversation_id, rollbackTo: 'signing' }, req });
  return json({ ok: true });
}

